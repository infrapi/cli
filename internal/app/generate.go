// Generated is what Generate wrote.
type Generated struct {
	// Files are the files written, relative to the project.
	Files []string
	// Ops are every operation of the contracts.
	Ops []op
	// Name is the API's, when the project serves one: its handlers'
	// package is internal/<Name>. Empty for a project of several APIs.
	Name string
}

// apiContracts are one API's contracts, its versions.
type apiContracts struct {
	name      string
	contracts []*contract
}

// byAPI groups contracts by API, in the order their files come.
func byAPI(contracts []*contract) []apiContracts {
	var out []apiContracts
	for _, c := range contracts {
		i := slices.IndexFunc(out, func(a apiContracts) bool { return a.name == c.Name })
		if i < 0 {
			out = append(out, apiContracts{name: c.Name})
			i = len(out) - 1
		}
		out[i].contracts = append(out[i].contracts, c)
	}
	return out
}

func apiNames(apis []apiContracts) []string {
	names := make([]string, len(apis))
	for i, a := range apis {
		names[i] = a.name
	}
	return names
}

// prefix is what an API's names in package api start with: nothing for a
// project of one API (Group, Roots), its exported name for several
// (SystemGroup, SystemRoots).
func prefix(apis []apiContracts, name string) string {
	if len(apis) == 1 {
		return ""
	}
	return exported(name)
}

// Generate writes the Go code of the project in root from its contracts,
// api/<name>-<version>.yaml: api/zz_generated.go, the schemas as types and
// the contracts embedded; internal/<name>/zz_generated.go, each API's
// Handlers and Register.
func Generate(root string) (Generated, error) {
	module, err := modulePath(root)
	if err != nil {
		return Generated{}, err
	}
	contracts, err := readContracts(filepath.Join(root, "api"))
	if err != nil {
		return Generated{}, err
	}
	apis := byAPI(contracts)
	var g Generated
	if len(apis) == 1 {
		g.Name = apis[0].name
	}
	types, err := typesFile(apis)
	if err != nil {
		return g, err
	}
	files := map[string][]byte{filepath.Join("api", "zz_generated.go"): types}
	for _, a := range apis {
		var ops []op
		names := map[string]string{}
		for i, c := range a.contracts {
			cops, err := c.operations("api.")
			if err != nil {
				return g, err
			}
			for j, o := range cops {
				if other, ok := names[o.Name]; ok {
					return g, fmt.Errorf("%s: operationId %s: %s has it already", c.File, o.Name, other)
				}
				names[o.Name] = c.File
				cops[j].Root = fmt.Sprintf("api.%sRoots[%d]", prefix(apis, a.name), i)
				cops[j].Rest = strings.TrimPrefix(o.Path, c.Root())
			}
			ops = append(ops, cops...)
		}
		if err := routable(ops); err != nil {
			return g, err
		}
		g.Ops = append(g.Ops, ops...)
		files[filepath.Join("internal", a.name, "zz_generated.go")] = handlersFile(a.name, module+"/api", ops)
	}

	for rel, src := range files {
		out, err := format.Source(src)
		if err != nil {
			return g, fmt.Errorf("%s: %w\n%s", rel, err, src)
		}
		path := filepath.Join(root, rel)
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, out) { //#nosec G304 -- the project's own file
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //#nosec G301 -- a source directory
			return g, err
		}
		if err := os.WriteFile(path, out, 0o644); err != nil { //#nosec G306 -- a source file
			return g, err
		}
		g.Files = append(g.Files, rel)
	}
	sort.Strings(g.Files)
	return g, nil
}

// modulePath is root's go.mod's module.
func modulePath(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod")) //#nosec G304 -- the project's own go.mod
	if err != nil {
		return "", err
	}
	m := regexp.MustCompile(`(?m)^module\s+(\S+)`).FindSubmatch(data)
	if m == nil {
		return "", fmt.Errorf("%s: no module line", filepath.Join(root, "go.mod"))
	}
	return string(m[1]), nil
}

const header = "// Code generated by infrapi-cli app generate from %s. DO NOT EDIT.\n\n"

// typesFile is api/zz_generated.go: per API its Group, its Roots (vars: a
// service may serve the API under another group, the routes follow), and
// for all of them Contracts and the schemas as Go types. A schema of the
// same name in two contracts is one type: written the same in both.
func typesFile(apis []apiContracts) ([]byte, error) {
	var files []string
	var body bytes.Buffer
	for _, a := range apis {
		p, first := prefix(apis, a.name), a.contracts[0]
		for _, c := range a.contracts {
			files = append(files, c.File)
		}
		fmt.Fprintf(&body, "// %sGroup is the %s API's group, its contracts' info.x-infrapi-group.\nvar %sGroup = %q\n\n", p, a.name, p, first.Group)
		fmt.Fprintf(&body, "// %sRoots are the %s API's roots, one per version: what server.NewServerGin\n// serves, and its routes' (Register).\nvar %sRoots = []string{", p, a.name, p)
		for _, c := range a.contracts {
			fmt.Fprintf(&body, "%q, ", c.Root())
		}
		body.WriteString("}\n\n")
		for _, c := range a.contracts {
			fmt.Fprintf(&body, "//go:embed %s\nvar contract%s%s []byte\n\n", c.File, p, exported(c.Version))
		}
	}
	body.WriteString("// Contracts are the contracts, as server.WithOpenAPI takes them: served\n// under each root's -/openapi/, and every request checked against them.\n")
	body.WriteString("func Contracts() []server.OpenAPISpec {\n\treturn []server.OpenAPISpec{\n")
	for _, a := range apis {
		p := prefix(apis, a.name)
		for i, c := range a.contracts {
			fmt.Fprintf(&body, "\t\t{Name: %q, Path: %q, Content: contract%s%s, Root: %sRoots[%d]},\n",
				c.Name+" "+c.Version, c.Name+"/"+c.Version+".yaml", p, exported(c.Version), p, i)
		}
	}
	body.WriteString("\t}\n}\n")

	seen := map[string]*contract{}
	for _, a := range apis {
		for _, c := range a.contracts {
			for _, name := range c.doc.Components.Schemas.keys {
				s := c.doc.Components.Schemas.values[name]
				if other, ok := seen[name]; ok {
					if !sameSchema(s, other.doc.Components.Schemas.values[name]) && other.Name != c.Name {
						return nil, fmt.Errorf("%s: components.schemas.%s: %s has another: one Go type, write them the same", c.File, name, other.File)
					}
					continue // the same type in two versions: the first one's
				}
				seen[name] = c
				if err := writeType(&body, name, s); err != nil {
					return nil, fmt.Errorf("%s: components.schemas.%s: %w", c.File, name, err)
				}
			}
		}
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, header, strings.Join(files, ", "))
	out.WriteString("// Package api is the contracts, and their schemas as Go types.\npackage api\n\nimport (\n\t_ \"embed\"\n")
	if strings.Contains(body.String(), "time.Time") {
		out.WriteString("\t\"time\"\n")
	}
	out.WriteString("\n\t\"github.com/infrapi/lib/pkg/server\"\n)\n\n")
	out.Write(body.Bytes())
	return out.Bytes(), nil
}

// sameSchema tells two schemas written the same.
func sameSchema(a, b *schema) bool {
	return fmt.Sprintf("%#v", flatten(a)) == fmt.Sprintf("%#v", flatten(b))
}

// flatten is s as plain values, for comparing.
func flatten(s *schema) any {
	if s == nil {
		return nil
	}
	props := map[string]any{}
	for _, k := range s.Properties.keys {
		props[k] = flatten(s.Properties.values[k])
	}
	var additional any
	if a := s.AdditionalProperties; a != nil {
		additional = []any{a.any, flatten(a.schema)}
	}
	return []any{s.Ref, s.Type, s.Format, s.Description, flatten(s.Items), s.Properties.keys, props, s.Required, additional, s.ReadOnly}
}

// writeType writes s as the Go type name, and its inline objects as
// <name><Field>.
func writeType(b *bytes.Buffer, name string, s *schema) error {
	if s.Description != "" {
		comment(b, "", name+": "+s.Description)
	}
	if s.Ref != "" || (s.Type != "object" && s.Type != "") || len(s.Properties.keys) == 0 {
		t, err := goType("", s)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "type %s %s\n\n", name, t)
		return nil
	}
	var nested []struct {
		name string
		s    *schema
	}
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, field := range s.Properties.keys {
		p := s.Properties.values[field]
		t := ""
		if p.Ref == "" && (p.Type == "object" || p.Type == "") && len(p.Properties.keys) > 0 {
			t = name + exported(field)
			nested = append(nested, struct {
				name string
				s    *schema
			}{t, p})
		} else {
			var err error
			if t, err = goType("", p); err != nil {
				return fmt.Errorf("%s: %w", field, err)
			}
		}
		if p.Description != "" {
			comment(b, "\t", p.Description)
		}
		tag := field
		if !slices.Contains(s.Required, field) {
			tag += ",omitzero"
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", exported(field), t, tag)
	}
	b.WriteString("}\n\n")
	for _, n := range nested {
		if err := writeType(b, n.name, n.s); err != nil {
			return err
		}
	}
	return nil
}

func comment(b io.Writer, indent, text string) {
	for _, l := range strings.Split(strings.TrimSpace(text), "\n") {
		_, _ = fmt.Fprintf(b, "%s// %s\n", indent, strings.TrimSpace(l))
	}
}

// signature is o's method signature, without its name.
func (o op) signature() string {
	args := []string{"ctx context.Context"}
	var strs []string
	for _, p := range o.Params {
		strs = append(strs, p.Ident)
	}
	if len(strs) > 0 {
		args = append(args, strings.Join(strs, ", ")+" string")
	}
	if o.Body != "" {
		args = append(args, "body "+o.Body)
	}
	ret := "error"
	if o.Result != "" {
		ret = "(" + o.Result + ", error)"
	}
	return "(" + strings.Join(args, ", ") + ") " + ret
}

// doc is o's comment: its summary, or its method and path.
func (o op) doc() string {
	if o.Summary != "" {
		return o.Name + ": " + o.Summary
	}
	return o.Name + " is " + o.Method + " " + o.Path + "."
}

// handlersFile is internal/<name>/zz_generated.go.
func handlersFile(name, apiImport string, ops []op) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, "the contracts in api/")
	fmt.Fprintf(&b, "package %s\n\n", name)
	head := b.Bytes()
	b = bytes.Buffer{}
	b.WriteString("// Handlers are the API's operations, one method per operationId of its\n// contracts. An error is answered as infrapi/lib renders it: an\n// infrapi/lib/pkg/errors error with its status, any other a 500.\ntype Handlers interface {\n")
	for _, o := range ops {
		comment(&b, "\t", o.doc())
		fmt.Fprintf(&b, "\t%s%s\n", o.Name, o.signature())
	}
	b.WriteString("}\n\n")

	b.WriteString("// Register routes h's operations on r, at their contracts' paths. The\n// contracts have checked a request before it gets here: server.WithOpenAPI.\nfunc Register(r gin.IRouter, h Handlers) {\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\tr.%s(%s+%q, func(c *gin.Context) {\n", o.Method, o.Root, o.GinRest())
		args := []string{"c.Request.Context()"}
		for _, p := range o.Params {
			if p.Query {
				args = append(args, fmt.Sprintf("c.Query(%q)", p.Name))
			} else {
				args = append(args, fmt.Sprintf("c.Param(%q)", p.Name))
			}
		}
		switch {
		case o.Body != "" && o.Optional:
			fmt.Fprintf(&b, "\t\tvar body %s\n\t\tif c.Request.ContentLength != 0 {\n\t\t\tif err := c.ShouldBindJSON(&body); err != nil {\n\t\t\t\tserver.AbortError(c, infraerrors.Invalid(\"%%s\", err))\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n", o.Body)
		case o.Body != "":
			fmt.Fprintf(&b, "\t\tvar body %s\n\t\tif err := c.ShouldBindJSON(&body); err != nil {\n\t\t\tserver.AbortError(c, infraerrors.Invalid(\"%%s\", err))\n\t\t\treturn\n\t\t}\n", o.Body)
		}
		if o.Body != "" {
			args = append(args, "body")
		}
		call := "h." + o.Name + "(" + strings.Join(args, ", ") + ")"
		if o.Result == "" {
			fmt.Fprintf(&b, "\t\tif err := %s; err != nil {\n\t\t\tserver.AbortError(c, err)\n\t\t\treturn\n\t\t}\n\t\tc.Status(%s)\n", call, statusConst(o.Status))
		} else {
			fmt.Fprintf(&b, "\t\tout, err := %s\n\t\tif err != nil {\n\t\t\tserver.AbortError(c, err)\n\t\t\treturn\n\t\t}\n", call)
			switch {
			case o.Stream != "":
				fmt.Fprintf(&b, "\t\tdefer func() { _ = out.Close() }()\n\t\tc.DataFromReader(%s, -1, %q, out, nil)\n", statusConst(o.Status), o.Stream)
			case strings.HasPrefix(o.Result, "[]"):
				fmt.Fprintf(&b, "\t\tif out == nil {\n\t\t\tout = %s{}\n\t\t}\n\t\tc.JSON(%s, out)\n", o.Result, statusConst(o.Status))
			default:
				fmt.Fprintf(&b, "\t\tc.JSON(%s, out)\n", statusConst(o.Status))
			}
		}
		b.WriteString("\t})\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// notImplemented is an operation not written yet: 501 Not Implemented.\n")
	fmt.Fprintf(&b, "func notImplemented(op string) error {\n\treturn infraerrors.New(http.StatusNotImplemented, %q+op, \"%%s is not implemented yet\", op)\n}\n", name+".")

	code := b.String()
	var imports []string
	if strings.Contains(code, "context.Context") {
		imports = append(imports, `"context"`)
	}
	if strings.Contains(code, "io.ReadCloser") {
		imports = append(imports, `"io"`)
	}
	if strings.Contains(code, "http.Status") {
		imports = append(imports, `"net/http"`)
	}
	imports = append(imports, "", `"github.com/gin-gonic/gin"`, "")
	if strings.Contains(code, "infraerrors.") {
		imports = append(imports, `infraerrors "github.com/infrapi/lib/pkg/errors"`)
	}
	if regexp.MustCompile(`\bserver\.[A-Za-z]+\(`).MatchString(code) {
		imports = append(imports, `"github.com/infrapi/lib/pkg/server"`)
	}
	if regexp.MustCompile(`\bapi\.[A-Z]`).MatchString(code) {
		imports = append(imports, "", strconv.Quote(apiImport))
	}
	return append(head, []byte("import (\n\t"+strings.Join(imports, "\n\t")+"\n)\n\n"+code)...)
}

// statusConst is code as net/http's constant.
func statusConst(code int) string {
	switch code {
	case 200:
		return "http.StatusOK"
	case 201:
		return "http.StatusCreated"
	case 202:
		return "http.StatusAccepted"
	case 204:
		return "http.StatusNoContent"
	}
	return fmt.Sprint(code)
}

// routable refuses paths gin cannot route together: two parameters of
// different names at the same place, .../environments/{name} beside
// .../environments/{environment}/modules. gin would panic at start.
func routable(ops []op) error {
	seen := map[string]string{} // a parameter's place: its name, and its path
	for _, o := range ops {
		segments := strings.Split(o.Path, "/")
		for i, seg := range segments {
			name, ok := strings.CutPrefix(seg, "{")
			if !ok {
				continue
			}
			name = strings.TrimSuffix(name, "}")
			place := strings.Join(segments[:i], "/")
			for j := range i {
				if strings.HasPrefix(segments[j], "{") {
					place = strings.Replace(place, segments[j], "{}", 1)
				}
			}
			if other, ok := seen[place]; ok {
				if otherName, otherPath, _ := strings.Cut(other, " "); otherName != name {
					return fmt.Errorf("%s: {%s} where %s has {%s}: gin routes a place under one name, rename one", o.Path, name, otherPath, otherName)
				}
				continue
			}
			seen[place] = name + " " + o.Path
		}
	}
	return nil
}
